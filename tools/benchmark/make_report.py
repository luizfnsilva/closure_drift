#!/usr/bin/env python3
"""Write tools/benchmark/BENCHMARK.md from tools/benchmark/results/*.json. `--check` compares instead."""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ORDER = ["torvalds/linux", "llvm/llvm-project", "rust-lang/rust", "python/cpython", "nodejs/node",
         "kubernetes/kubernetes", "git/git", "Azure/azure-sdk-for-python",
         "googleapis/google-cloud-python", "DefinitelyTyped/DefinitelyTyped"]
RUNS = [("B1", "default"), ("B3", "every tag"), ("B4", "`--would-tag`"), ("B5", "`--at commits`")]


def cell(run):
    if run is None:
        return "—"
    if run["timed_out"]:
        return "**did not finish in 40 min**"
    answer = run.get("verdict") or ("refusal" if run["exit"] == 2 else f"exit {run['exit']}")
    return f"{run['seconds']:.0f} s · {run['peak_mb']:.0f} MB · {answer}"


def main():
    rows = {}
    for f in sorted((HERE / "results").glob("*.json")):
        r = json.loads(f.read_text(encoding="utf-8"))
        rows[r["repository"]] = r
    any_row = next(iter(rows.values()))
    m = any_row["machine"]
    out = ["# Large repositories — what 0.9.0 did", "",
           "Generated by `tools/benchmark/make_report.py` from `results/`. Protocol, written first: "
           "[`PREREGISTRATION.md`](PREREGISTRATION.md).", "",
           f"Detector sha256 `{any_row['detector_sha256']}`. One run each, on a GitHub-hosted runner "
           f"({m['platform']}, {m['cpus']} CPUs, {m.get('memory_mb', '?')} MB, {m['git']}, Python {m['python']}). "
           "Times on shared runners vary; these are single measurements.", "",
           "## The repositories", "",
           "| repository | files at HEAD | tags (at commits) | commits | clone |", "|---|---|---|---|---|"]
    for slug in ORDER:
        r = rows.get(slug)
        if r is None:
            out.append(f"| `{slug}` | no result file | | | |")
        elif r["clone"]["exit"] != 0:
            out.append(f"| `{slug}` | clone failed: {r['clone'].get('stderr_first', '')} | | | |")
        else:
            c = r["clone"]
            out.append(f"| `{slug}` | {c['files_at_head']:,} | {c['tags']:,} ({c['tags_at_commits']:,}) | {c['commits_from_head']:,} | "
                       f"{c['disk_mb']:,} MB in {c['seconds']:.0f} s |")
    out += ["", "## Time, peak memory, answer", "",
            "| repository | " + " | ".join(t for _i, t in RUNS) + " |", "|---|" + "---|" * len(RUNS)]
    for slug in ORDER:
        r = rows.get(slug)
        if r and r["clone"]["exit"] == 0:
            out.append(f"| `{slug}` | " + " | ".join(cell(r["runs"].get(i)) for i, _t in RUNS) + " |")
    out += ["", "A refusal here is the tool finding no version label by its default rules; nothing was "
            "tuned per repository.", "",
            "## Coverage, every tag", "",
            "| repository | version read from | tags scanned | compared | labels | in drift |", "|---|---|---|---|---|---|"]
    for slug in ORDER:
        r = rows.get(slug)
        b1 = r and r["runs"].get("B3") or {}
        if "verdict" in b1 and "labels" in b1:
            out.append(f"| `{slug}` | {('`' + b1['version_file'] + '`') if b1.get('version_file') else 'nothing at HEAD; found at older tags'} | {b1['publication_points_scanned']:,} | "
                       f"{b1['publication_points_compared']:,} | {b1['labels']:,} | "
                       f"{b1['labels_covering_multiple_closures']:,} |")
        elif r and r["clone"]["exit"] == 0:
            out.append(f"| `{slug}` | {b1.get('stderr_first', '')[:70] or b1.get('verdict', '—')} | | | | |")
    out += ["", "Run B3 (`--max-commits 1000000`). A label in drift here is not a finding about the "
            "project: no closure and no tag family was configured.", "",
            "## Against the oracle", "",
            "`--compare` on two pairs of tags, and `tests/oracle.py` on the same pairs.", "",
            "| repository | pair | files in closure | paths differing | ids and counts | path lists | detector | oracle |",
            "|---|---|---|---|---|---|---|---|"]
    for slug in ORDER:
        r = rows.get(slug)
        for label, check in ((r or {}).get("oracle") or {}).items():
            d, o = r["runs"][f"B6_{label}"], r["runs"][f"B7_{label}"]
            times = f"{d['seconds']:.1f} s · {d['peak_mb']:.0f} MB | {o['seconds']:.1f} s · {o['peak_mb']:.0f} MB"
            if check["compared"]:
                out.append(f"| `{slug}` | {label.replace('_', ' → ')} | {check['files'][0]:,} and {check['files'][1]:,} | "
                           f"{check['paths_differing']:,} | {'agree' if check['ids_and_counts_agree'] else '**DIFFER**'} | "
                           f"{'agree' if check['path_lists_agree'] else '**DIFFER**'} | {times} |")
            else:
                out.append(f"| `{slug}` | {label.replace('_', ' → ')} | not compared: {check.get('reason', '')[:80]} | | | | {times} |")
    out += ["", "## Failures, by the ids of the pre-registration", ""]
    failures = [(slug, f) for slug in ORDER for f in (rows.get(slug) or {}).get("failures", [])]
    missing = [slug for slug in ORDER if slug not in rows]
    if not failures and not missing:
        out.append("None of F1–F6 occurred.")
    for slug, f in failures:
        out.append(f"- `{slug}`: {f}")
    for slug in missing:
        out.append(f"- `{slug}`: no result file")
    same = [slug for slug in ORDER if slug in rows and "B2" in rows[slug]["runs"]
            and rows[slug]["runs"]["B1"]["stdout_sha256"] == rows[slug]["runs"]["B2"]["stdout_sha256"]]
    out += ["", f"The default run printed the same bytes twice in {len(same)} of {len(rows)} repositories.", ""]
    text = "\n".join(out)
    target = HERE / "BENCHMARK.md"
    if "--check" in sys.argv:
        if target.read_text(encoding="utf-8") != text:
            print("BENCHMARK.md is not what make_report.py writes from results/", file=sys.stderr)
            return 1
        print("BENCHMARK.md matches results/")
        return 0
    target.write_bytes(text.encode("utf-8"))
    print(f"wrote {target.name}: {len(rows)} repositories, {len(failures)} failures")
    return 0


if __name__ == "__main__":
    sys.exit(main())
